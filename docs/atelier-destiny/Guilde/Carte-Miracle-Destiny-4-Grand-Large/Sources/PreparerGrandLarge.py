 for contour in contours:
  d.polygon([(pad+round((w-1)*x/100),pad+round((h-1)*y/100)) for x,y in ps(contour)],fill='#bc945c')
 im.resize((im.width*3,im.height*3),Image.Resampling.NEAREST).save(R/f'{name}-Silhouette.png',optimize=True)

