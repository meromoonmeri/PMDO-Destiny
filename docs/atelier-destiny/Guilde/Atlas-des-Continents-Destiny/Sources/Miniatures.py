NN=Image.Resampling.NEAREST
class T:
    def __init__(self,w,h):self.im=Image.new('RGBA',(w,h));self.d=ImageDraw.Draw(self.im)
    def p(self,pts,fill,edge=None):self.d.polygon(pts,fill=fill,outline=edge)
    def l(self,pts,fill,w=1):self.d.line(pts,fill=fill,width=w)
    def r(self,box,fill,edge=None):self.d.rectangle(box,fill=fill,outline=edge)
    def e(self,box,fill,edge=None):self.d.ellipse(box,fill=fill,outline=edge)
    def pt(self,p,fill):self.d.point(p,fill=fill)
    def put(self,a,x,y):self.im.alpha_composite(a,(x,y))
    def cut(self):return self.im.crop(self.im.getbbox())

def fit(a,w,h=None):
    if w is None:return a
    return a.resize((w,max(2,round(a.height*w/a.width)) if h is None else h),NN)

